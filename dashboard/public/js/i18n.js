  const state = {
    lang: localStorage.getItem('brobot.lang') || 'en',
    listeners: []
  };

  function t(key, vars) {
    const dict = translations[state.lang] || translations.en;
    let text = dict[key] ?? translations.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.split(`{${k}}`).join(String(v));
      }
    }
    return text;
  }

  function applyStatic() {
    document.documentElement.lang = state.lang;
    document.documentElement.dir = state.lang === 'ar' ? 'rtl' : 'ltr';
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
  }

  function setLang(lang) {
    state.lang = lang === 'ar' ? 'ar' : 'en';
    localStorage.setItem('brobot.lang', state.lang);
    applyStatic();
    document.dispatchEvent(new CustomEvent('brobot:lang', { detail: { lang: state.lang } }));
  }

  function toggleLang() {
    setLang(state.lang === 'ar' ? 'en' : 'ar');
  }

  applyStatic();

  document.addEventListener('DOMContentLoaded', () => {
    applyStatic();
    document.querySelectorAll('.lang-toggle').forEach((btn) => {
      btn.addEventListener('click', toggleLang);
    });
  });

  window.I18N = { t, setLang, toggleLang, applyStatic, get lang() { return state.lang; } };
  window.t = t;
